def 场景丙():
    """换绑与出站并发 30 轮：行程卡号必须恒等于开腿卡号/刷卡卡号。"""
    import sqlite3
    print("场景丙：换绑×出站并发，不允许撕裂")
    轮 = 30
    for i in range(轮):
        装({"批次编号": f"setup-{i}", "事件": [
            {"事件编号": f"s{i}", "卡号": "卡M", "站点键": "站A", "方向": "进站",
             "事件时": "2026-11-22T08:00:00Z", "处理时": "2026-11-22T08:00:01Z"},
        ]})
        屏障 = threading.Barrier(2)
        错 = []

        def 换绑线程():
            try:
                屏障.wait()
                from app.services import 换绑
                from app.db import 库路径
                c = sqlite3.connect(库路径, timeout=10)
                c.row_factory = sqlite3.Row
                c.execute("PRAGMA busy_timeout=10000")
                c.execute("BEGIN IMMEDIATE")
                换绑.做换绑(c, {"换绑键": f"rb-C{i}", "旧卡": "卡M", "新卡": f"卡N{i}",
                                "事件时": "2026-11-22T09:00:00Z"}, 来源="并发")
                c.commit()
                c.close()
            except Exception as e:
                错.append(f"换绑线程:{e}")

        def 出站线程():
            try:
                屏障.wait()
                装({"批次编号": f"out-{i}", "事件": [
                    {"事件编号": f"o{i}", "卡号": "卡M", "站点键": "站B", "方向": "出站",
                     "事件时": "2026-11-22T09:05:00Z", "处理时": "2026-11-22T09:05:01Z"},
                ]})
            except Exception as e:
                错.append(f"出站线程:{e}")

        t1, t2 = threading.Thread(target=换绑线程), threading.Thread(target=出站线程)
        t1.start(); t2.start(); t1.join(); t2.join()
        检查(f"轮{i}无线程异常", not 错, str(错))

        for t in 查("SELECT * FROM 行程账"):
            腿 = 查("SELECT * FROM 开腿账 WHERE 进站事件编号=?", (t["进站事件编号"],))[0]
            刷 = {r["事件编号"]: r for r in 查("SELECT * FROM 刷卡点 WHERE 行程键=?", (t["行程键"],))}
            一致 = (t["卡号"] == 腿["卡号"]
                    and 刷[t["进站事件编号"]]["卡号"] == t["卡号"]
                    and 刷[t["出站事件编号"]]["卡号"] == t["卡号"])
            检查(f"轮{i}行程{t['行程键']}行程/开腿/刷卡三卡号一致", 一致,
                 f"行程{t['卡号']} 腿{腿['卡号']}")
        腿 = 查("SELECT * FROM 开腿账 WHERE 开腿键=?", (f"腿-s{i}",))[0]
        rb = 查("SELECT * FROM 卡号换绑 WHERE 换绑键=?", (f"rb-C{i}",))
        if rb and rb[0]["valid"] and 腿["状态"] == "已旁路":
            检查(f"轮{i}切断腿卡号仍是旧卡且原因正确",
                 腿["卡号"] == "卡M" and 腿["旁路原因"] == "换绑切断")
    print(f"  并发轮数={轮} 完成")


