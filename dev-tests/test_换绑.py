def 检查(名, 条件, 详情=""):
    if 条件:
        print(f"  ✓ {名}")
    else:
        raise AssertionError(f"{名} {详情}")


def 装(体):
    from app.services import 装载
    return 装载.装一批(体)


def 查(sql, 参数=()):
    from app.db import 连接
    c = 连接()
    try:
        return [dict(r) for r in c.execute(sql, 参数)]
    finally:
        c.close()


